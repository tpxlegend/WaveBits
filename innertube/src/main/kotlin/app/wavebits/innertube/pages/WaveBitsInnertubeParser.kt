            } == true

            SongItem(
                id = vid,
                title = title,
                artists = artists,
                album = album,
                duration = durationSec,
                thumbnail = thumb,
                explicit = explicit,
                endpoint = WatchEndpoint(
                    videoId = vid,
                    playlistId = endpoint?.playlistId ?: automixPlaylistId,
                ),
            )
        }.orEmpty()

        val continuation = extractContinuationToken(playlistPanel?.arr("continuations")) ?: inlineContToken

        val lyricsBrowse = tabs?.getOrNull(1)
            ?.obj("tabRenderer")
            ?.obj("endpoint")
            ?.obj("browseEndpoint")
        val lyricsEndpoint = lyricsBrowse?.str("browseId")?.let { bId ->
            NavigationEndpoint(
                browseEndpoint = BrowseEndpoint(
                    browseId = bId,
                    params = lyricsBrowse.str("params"),
                )
            )
        }

        val resolvedEndpoint = if (endpoint?.playlistId == null && !automixPlaylistId.isNullOrBlank()) {
            WatchEndpoint(
                videoId = endpoint?.videoId ?: songs.firstOrNull()?.id,
                playlistId = automixPlaylistId,
            )
        } else {
            endpoint
        }

        return NextResult(
            endpoint = resolvedEndpoint,
            continuation = continuation,
            items = songs,
            lyricsEndpoint = lyricsEndpoint,
        )
    }

    // -------------------------------------------------------------------------
    // Library (`FEmusic_library_landing`, `FEmusic_liked_playlists`, `FEmusic_liked_albums`)
    // -------------------------------------------------------------------------

    fun parseLibrary(root: JsonObject): LibraryPage {
        captureVisitorData(root)
        val home = parseHome(root)
        val items = mutableListOf<YTItem>()
        items.addAll(home.sections.flatMap { it.items })

        var fallbackContinuation: String? = null
        fun walkLibraryItems(el: JsonElement) {
            when (el) {
                is JsonObject -> {
                    el.obj("musicTwoRowItemRenderer")?.let(::parseTwoRowItem)?.let(items::add)
                    el.obj("musicResponsiveListItemRenderer")?.let(::parseResponsiveListItem)?.let(items::add)
                    if (fallbackContinuation == null) {
                        fallbackContinuation = el.obj("nextContinuationData")?.str("continuation")?.takeIf { it.isNotBlank() }
                            ?: el.obj("continuationItemRenderer")?.obj("continuationEndpoint")?.obj("continuationCommand")?.str("token")?.takeIf { it.isNotBlank() }
                    }
                    for ((_, v) in el) walkLibraryItems(v)
                }
                is JsonArray -> for (child in el) walkLibraryItems(child)
                else -> {}
            }
        }
        root.obj("contents")?.let(::walkLibraryItems)
        root.obj("continuationContents")?.let(::walkLibraryItems)
        root.arr("onResponseReceivedActions")?.let(::walkLibraryItems)

        return LibraryPage(
            items = items.distinctBy { "${it::class.simpleName}:${it.id}" },
            continuation = home.continuation ?: fallbackContinuation,
        )
    }

    // -------------------------------------------------------------------------
    // Account Menu (`account/account_menu`)
    // -------------------------------------------------------------------------

    fun parseAccountInfo(root: JsonObject): AccountInfo? {
        captureVisitorData(root)
        var foundName: String? = null
        var foundThumb: String? = null

        fun walk(el: JsonElement) {
            if (!foundName.isNullOrBlank()) return
            when (el) {
                is JsonObject -> {
                    el.obj("activeAccountHeaderRenderer")?.let { header ->
                        foundName = header.runsText("accountName")
                            ?: header.runsText("channelHandle")
                            ?: header.runsText("email")
                        foundThumb = upscaleThumbnail(header.obj("accountPhoto")?.thumbnailUrl())
                        if (!foundName.isNullOrBlank()) return
                    }
                    el.obj("accountItem")?.let { item ->
                        val isSelected = item["isSelected"]?.jsonPrimitive?.booleanOrNull ?: true
                        if (isSelected) {
                            foundName = item.runsText("accountName") ?: item.runsText("channelHandle")
                            foundThumb = upscaleThumbnail(item.obj("accountPhoto")?.thumbnailUrl())
                        }
                    }
                    for ((_, v) in el) walk(v)
                }
                is JsonArray -> for (child in el) walk(child)
                else -> {}
            }
        }
        walk(root)
        val name = foundName?.trim()?.takeIf { it.isNotEmpty() } ?: return null
        return AccountInfo(name = name, thumbnailUrl = foundThumb)
    }

    fun parseAccounts(root: JsonObject): List<YouTubeChannel> {
        captureVisitorData(root)
        val channels = mutableListOf<YouTubeChannel>()
        fun walk(el: JsonElement) {
            when (el) {
                is JsonObject -> {
                    el.obj("accountItem")?.let { item ->
                        val name = item.runsText("accountName") ?: return@let
                        val thumb = upscaleThumbnail(item.obj("accountPhoto")?.thumbnailUrl())
                        val selected = item["isSelected"]?.jsonPrimitive?.booleanOrNull == true
                        val tokens = item.obj("serviceEndpoint")
                            ?.obj("selectActiveIdentityEndpoint")
                            ?.arr("supportedTokens")
                        var pageId = ""
                        var dataSyncId: String? = null
                        tokens?.forEach { tok ->
                            tok.obj("pageIdToken")?.str("pageId")?.let { pageId = it }
                            tok.obj("datasyncIdToken")?.str("datasyncIdToken")?.let { dataSyncId = it }
                        }
                        channels.add(
                            YouTubeChannel(
                                name = name,
                                pageId = pageId,
                                dataSyncId = dataSyncId,
                                thumbnailUrl = thumb,
                                selected = selected,
                            )
                        )
                    }
                    for ((_, v) in el) walk(v)
                }
                is JsonArray -> for (child in el) walk(child)
                else -> {}
            }
        }
        walk(root)
        return channels
    }

    // -------------------------------------------------------------------------
    // Search Suggestions (`music/get_search_suggestions`)
    // -------------------------------------------------------------------------

    fun parseSearchSuggestions(root: JsonObject): SearchSuggestions {
        captureVisitorData(root)
        val queries = mutableListOf<String>()
        root.arr("contents")?.forEach { sec ->
            sec.obj("searchSuggestionsSectionRenderer")?.arr("contents")?.forEach { item ->
                val q = item.obj("searchSuggestionRenderer")
                    ?.obj("navigationEndpoint")
                    ?.obj("searchEndpoint")
                    ?.str("query")
                    ?: item.obj("searchSuggestionRenderer")?.runsText("suggestion")
                if (!q.isNullOrBlank()) queries.add(q)
            }
        }
        return SearchSuggestions(queries = queries.distinct())
    }

