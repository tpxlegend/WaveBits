        tabSection?.obj("musicResponsiveHeaderRenderer")?.let { return it }
        tabSection?.obj("musicEditablePlaylistDetailHeaderRenderer")?.obj("header")?.obj("musicResponsiveHeaderRenderer")?.let { return it }
        tabSection?.obj("musicDetailHeaderRenderer")?.let { return it }
        return null
    }

