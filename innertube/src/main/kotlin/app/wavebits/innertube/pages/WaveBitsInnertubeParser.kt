    fun parseHistorySongs(root: JsonObject): List<SongItem> {
        captureVisitorData(root)
        val out = mutableListOf<SongItem>()
        val seen = HashSet<String>()

        fun walk(el: JsonElement) {
            if (out.size >= 24) return
            when (el) {
                is JsonObject -> {
                    el.obj("musicResponsiveListItemRenderer")?.let { r ->
                        val item = parseResponsiveListItem(r)
                        if (item is SongItem && isValidVideoId(item.id) && seen.add(item.id)) {
                            out.add(item)
                        }
                    }
                    el.obj("musicTwoRowItemRenderer")?.let { r ->
                        val item = parseTwoRowItem(r)
                        if (item is SongItem && isValidVideoId(item.id) && seen.add(item.id)) {
                            out.add(item)
                        }
                    }
                    for ((_, v) in el) walk(v)
                }
                is JsonArray -> for (child in el) walk(child)
                else -> {}
            }
        }

        walk(root)
        return out
    }

    private fun isValidVideoId(id: String): Boolean {
        if (id.isBlank()) return false
        return !id.startsWith("UC") &&
            !id.startsWith("VL") &&
            !id.startsWith("PL") &&
            !id.startsWith("MPRE") &&
            !id.startsWith("OLAK") &&
            !id.startsWith("RD") &&
            !id.startsWith("FE")
    }

