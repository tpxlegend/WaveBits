    fun parsePlaylist(root: JsonObject, playlistId: String): PlaylistPage {
        captureVisitorData(root)
        val cleanId = if (playlistId == "FEmusic_liked_videos") "LM" else playlistId.removePrefix("VL")

        // Header can be in singleColumnBrowseResultsRenderer or twoColumnBrowseResultsRenderer
        val headerRenderer = findPlaylistHeader(root)
        val title = headerRenderer?.runsText("title")
            ?: (if (cleanId == "LM") "Liked Music" else "Playlist")
        val authorText = headerRenderer?.runsText("straplineTextOne")
            ?: headerRenderer?.runsText("subtitle")
            ?: "YouTube Music"
        val songCountText = headerRenderer?.runsText("secondSubtitle")
        val thumb = upscaleThumbnail(
            headerRenderer?.obj("thumbnail")?.obj("musicThumbnailRenderer")?.thumbnailUrl()
                ?: headerRenderer?.obj("thumbnail")?.obj("croppedSquareThumbnailRenderer")?.thumbnailUrl()
        )

        val songs = mutableListOf<SongItem>()
        var continuation: String? = null

        fun collectFromShelf(shelf: JsonObject) {
            shelf.arr("contents")?.forEach { el ->
                val r = el.obj("musicResponsiveListItemRenderer") ?: return@forEach
                val item = parseResponsiveListItem(r, fallbackThumb = thumb)
                if (item is SongItem) songs.add(item)
            }
            if (continuation == null) {
                continuation = extractContinuationToken(shelf.arr("continuations"))
                    ?: extractContinuationToken(shelf.arr("contents"))
            }
        }

        fun collectFromSectionElement(sec: JsonElement) {
            sec.obj("musicPlaylistShelfRenderer")?.let(::collectFromShelf)
            sec.obj("musicShelfRenderer")?.let(::collectFromShelf)
            sec.obj("itemSectionRenderer")?.arr("contents")?.forEach { inner ->
                inner.obj("musicPlaylistShelfRenderer")?.let(::collectFromShelf)
                inner.obj("musicShelfRenderer")?.let(::collectFromShelf)
            }
        }

        // Check twoColumnBrowseResultsRenderer secondaryContents and tabs
        val twoCol = root.obj("contents")?.obj("twoColumnBrowseResultsRenderer")
        twoCol?.obj("secondaryContents")
            ?.obj("sectionListRenderer")
            ?.arr("contents")
            ?.forEach(::collectFromSectionElement)
        if (songs.isEmpty()) {
            twoCol?.arr("tabs")?.forEach { tabEl ->
                val tabContent = tabEl.obj("tabRenderer")?.obj("content")
                tabContent?.obj("sectionListRenderer")
                    ?.arr("contents")
                    ?.forEach(::collectFromSectionElement)
                tabContent?.obj("musicPlaylistShelfRenderer")?.let(::collectFromShelf)
                tabContent?.obj("musicShelfRenderer")?.let(::collectFromShelf)
            }
        }

        // Check singleColumnBrowseResultsRenderer
        if (songs.isEmpty()) {
            root.obj("contents")
                ?.obj("singleColumnBrowseResultsRenderer")
                ?.arr("tabs")
                ?.forEach { tabEl ->
                    val tabContent = tabEl.obj("tabRenderer")?.obj("content")
                    tabContent?.obj("sectionListRenderer")
                        ?.arr("contents")
                        ?.forEach(::collectFromSectionElement)
                    tabContent?.obj("musicPlaylistShelfRenderer")?.let(::collectFromShelf)
                    tabContent?.obj("musicShelfRenderer")?.let(::collectFromShelf)
                }
        }

        // Check continuationContents or onResponseReceivedActions if this was a continuation or reload
        if (songs.isEmpty()) {
            root.obj("continuationContents")?.obj("musicPlaylistShelfContinuation")?.let(::collectFromShelf)
            root.obj("continuationContents")?.obj("musicShelfContinuation")?.let(::collectFromShelf)
            root.arr("onResponseReceivedActions")?.forEach { action ->
                val appendItems = action.obj("appendContinuationItemsAction")?.arr("continuationItems")
                    ?: action.obj("reloadContinuationItemsCommand")?.arr("continuationItems")
                appendItems?.forEach { el ->
                    el.obj("musicResponsiveListItemRenderer")?.let { r ->
                        val item = parseResponsiveListItem(r, fallbackThumb = thumb)
                        if (item is SongItem) songs.add(item)
                    }
                    collectFromSectionElement(el)
                }
                if (continuation == null) {
                    continuation = extractContinuationToken(appendItems)
                }
            }
        }

        // Deep fallback walk if songs are still empty (e.g., nested renderers in VLLM / FEmusic_liked_videos)
        if (songs.isEmpty()) {
            val seen = HashSet<String>()
            fun walkSongs(el: JsonElement) {
                if (songs.size >= 200) return
                when (el) {
                    is JsonObject -> {
                        el.obj("musicResponsiveListItemRenderer")?.let { r ->
                            val item = parseResponsiveListItem(r, fallbackThumb = thumb)
                            if (item is SongItem && isValidVideoId(item.id) && seen.add(item.id)) {
                                songs.add(item)
                            }
                        }
                        for ((_, v) in el) walkSongs(v)
                    }
                    is JsonArray -> for (child in el) walkSongs(child)
                    else -> {}
                }
            }
            root.obj("contents")?.let(::walkSongs)
        }

        val finalThumb = thumb ?: songs.firstOrNull()?.thumbnail

        return PlaylistPage(
            playlist = PlaylistItem(
                id = cleanId,
                title = title,
                author = Artist(authorText, null),
                songCountText = songCountText ?: "${songs.size} songs",
                thumbnail = finalThumb,
                playEndpoint = WatchEndpoint(playlistId = cleanId),
                shuffleEndpoint = WatchEndpoint(playlistId = cleanId, params = "wAEB8gECKAE%3D"),
                radioEndpoint = WatchEndpoint(playlistId = "RDAMPL$cleanId"),
            ),
            songs = songs.distinctBy { it.id },
            continuation = continuation,
        )
    }

    fun parseAlbum(root: JsonObject, browseId: String): AlbumPage {
        captureVisitorData(root)
        val headerRenderer = findPlaylistHeader(root)
        val title = headerRenderer?.runsText("title") ?: "Album"

        val straplineRuns = headerRenderer?.obj("straplineTextOne")?.arr("runs")
            ?: headerRenderer?.obj("subtitle")?.arr("runs")
        val artists = straplineRuns?.mapNotNull { run ->
            val text = run.str("text")?.trim()?.takeIf { it.isNotEmpty() && !isMetadataNoise(it) && it != "•" && it != "&" && it != "," }
                ?: return@mapNotNull null
            val bId = run.obj("navigationEndpoint")?.obj("browseEndpoint")?.str("browseId")
            Artist(text, bId)
        }.orEmpty().ifEmpty { listOf(Artist("YouTube Music", null)) }

        val year = headerRenderer?.obj("subtitle")?.arr("runs")
            ?.mapNotNull { it.str("text")?.trim() }
            ?.firstOrNull { YEAR_REGEX.matches(it) }
            ?.toIntOrNull()

        val thumb = upscaleThumbnail(
            headerRenderer?.obj("thumbnail")?.obj("musicThumbnailRenderer")?.thumbnailUrl()
                ?: headerRenderer?.obj("thumbnail")?.obj("croppedSquareThumbnailRenderer")?.thumbnailUrl()
        ).orEmpty()

        val fallbackAlbum = Album(title, browseId)
        val fallbackArtist = artists.firstOrNull()

        val songs = mutableListOf<SongItem>()
        fun collectAlbumShelf(sec: JsonElement) {
            val shelf = sec.obj("musicShelfRenderer")
                ?: sec.obj("musicPlaylistShelfRenderer")
                ?: sec.obj("itemSectionRenderer")?.arr("contents")?.firstNotNullOfOrNull {
                    it.obj("musicShelfRenderer") ?: it.obj("musicPlaylistShelfRenderer")
                }
            shelf?.arr("contents")?.forEach { el ->
                val r = el.obj("musicResponsiveListItemRenderer") ?: return@forEach
                val item = parseResponsiveListItem(
                    r,
                    fallbackArtist = fallbackArtist,
                    fallbackAlbum = fallbackAlbum,
                    fallbackThumb = thumb,
                )
                if (item is SongItem) songs.add(item)
            }
        }

        val twoCol = root.obj("contents")?.obj("twoColumnBrowseResultsRenderer")
        twoCol?.obj("secondaryContents")
            ?.obj("sectionListRenderer")
            ?.arr("contents")
            ?.forEach(::collectAlbumShelf)

        if (songs.isEmpty()) {
            root.obj("contents")
                ?.obj("singleColumnBrowseResultsRenderer")
                ?.arr("tabs")
                ?.firstOrNull()
                ?.obj("tabRenderer")
                ?.obj("content")
                ?.obj("sectionListRenderer")
                ?.arr("contents")
                ?.forEach(::collectAlbumShelf)
        }

        val playlistId = songs.firstOrNull()?.endpoint?.playlistId ?: browseId

        return AlbumPage(
            album = AlbumItem(
                browseId = browseId,
                playlistId = playlistId,
                title = title,
                artists = artists,
                year = year,
                thumbnail = thumb.ifBlank { songs.firstOrNull()?.thumbnail.orEmpty() },
            ),
            songs = songs,
        )
    }

