/**
 * Resilient JSON parser for WaveBits InnerTube responses.
 * Parses YouTube Music InnerTube `browse`, `next`, `explore`, `history`,
 * and `get_search_suggestions` responses into `app.wavebits.innertube` models.
 */
object WaveBitsInnertubeParser {

    private val DURATION_REGEX = Regex("""^\d{1,2}:\d{2}(:\d{2})?$""")
    private val YEAR_REGEX = Regex("""^(19|20)\d{2}$""")

    private val NON_ARTIST_TOKENS = setOf(
        "song", "video", "album", "ep", "single", "playlist", "artist", "podcast", "episode", "profile",
        "auto-generated by youtube",
    )

    private fun isMetadataNoise(text: String): Boolean {
        val lower = text.trim().lowercase()
        if (lower in NON_ARTIST_TOKENS) return true
        if (lower.endsWith(" views") || lower.endsWith(" view")) return true
        if (lower.endsWith(" plays") || lower.endsWith(" play")) return true
        if (lower.endsWith(" likes") || lower.endsWith(" like")) return true
        if (lower.endsWith(" subscribers") || lower.endsWith(" subscriber")) return true
        if (lower.endsWith(" songs") || lower.endsWith(" song") || lower.endsWith(" tracks")) return true
        if (DURATION_REGEX.matches(lower)) return true
        if (YEAR_REGEX.matches(lower)) return true
        return false
    }

    fun captureVisitorData(root: JsonObject) {
        if (YouTube.visitorData.isNullOrBlank()) {
            val vd = root.obj("responseContext")?.str("visitorData")
            if (!vd.isNullOrBlank()) {
                YouTube.visitorData = vd
            }
        }
    }

    fun upscaleThumbnail(url: String?): String? {
        if (url.isNullOrBlank()) return null
        return url
            .replace(Regex("""=w\d+-h\d+"""), "=w544-h544")
            .replace(Regex("""=s\d+"""), "=s544")
    }

    // -------------------------------------------------------------------------
    // YouTube Music Home (`FEmusic_home`, `FEmusic_new_releases`, `FEmusic_explore`, continuations)
    // -------------------------------------------------------------------------

    fun parseHome(root: JsonObject): HomePage {
        captureVisitorData(root)

        // Check if this is a continuation response first
        val continuationPage = parseHomeContinuation(root)
        if (continuationPage.sections.isNotEmpty() || continuationPage.continuation != null) {
            // If it also has tabs (initial load), fall through; otherwise return continuation
            val hasTabs = root.obj("contents")
                ?.obj("singleColumnBrowseResultsRenderer")
                ?.arr("tabs") != null
            if (!hasTabs) return continuationPage
        }

        val tabs = root.obj("contents")
            ?.obj("singleColumnBrowseResultsRenderer")
            ?.arr("tabs")
            ?: root.obj("contents")
                ?.obj("twoColumnBrowseResultsRenderer")
                ?.arr("tabs")
        val selectedTabContent = tabs
            ?.firstOrNull { it.obj("tabRenderer")?.get("selected")?.jsonPrimitive?.booleanOrNull == true }
            ?.obj("tabRenderer")
            ?.obj("content")
            ?: tabs?.firstOrNull()?.obj("tabRenderer")?.obj("content")

        val sectionList = selectedTabContent?.obj("sectionListRenderer")
            ?: root.obj("contents")?.obj("sectionListRenderer")
            ?: root.obj("contents")?.obj("twoColumnBrowseResultsRenderer")
                ?.obj("secondaryContents")?.obj("sectionListRenderer")

        val chips = sectionList?.obj("header")
            ?.obj("chipCloudRenderer")
            ?.arr("chips")
            ?.mapNotNull { chipEl ->
                val chip = chipEl.obj("chipCloudChipRenderer") ?: return@mapNotNull null
                val text = chip.runsText("text") ?: return@mapNotNull null
                val browseEndpoint = chip.obj("navigationEndpoint")?.obj("browseEndpoint")
                val params = browseEndpoint?.str("params") ?: return@mapNotNull null
                val browseId = browseEndpoint.str("browseId") ?: "FEmusic_home"
                HomeChipItem(
                    title = text,
                    endpoint = NavigationEndpoint(
                        browseEndpoint = BrowseEndpoint(
                            browseId = browseId,
                            params = params,
                        )
                    )
                )
            }.orEmpty()

        val sections = mutableListOf<HomeSection>()
        sectionList?.arr("contents")?.forEach { secEl ->
            val itemSecContents = secEl.obj("itemSectionRenderer")?.arr("contents")
            if (itemSecContents != null) {
                itemSecContents.forEach { innerEl ->
                    parseHomeSection(innerEl)?.takeIf { it.items.isNotEmpty() }?.let(sections::add)
                }
            } else {
                parseHomeSection(secEl)?.takeIf { it.items.isNotEmpty() }?.let(sections::add)
            }
        }

        // Also handle tabRenderer.content directly holding gridRenderer or musicShelfRenderer
        if (sections.isEmpty() && selectedTabContent != null) {
            parseHomeSection(selectedTabContent)?.takeIf { it.items.isNotEmpty() }?.let(sections::add)
        }

        val continuation = extractContinuationToken(sectionList?.arr("continuations"))
            ?: extractContinuationToken(sectionList?.arr("contents"))
            ?: sectionList?.arr("contents")?.firstNotNullOfOrNull { secEl ->
                secEl.obj("gridRenderer")?.let { g ->
                    extractContinuationToken(g.arr("continuations")) ?: extractContinuationToken(g.arr("items"))
                } ?: secEl.obj("musicShelfRenderer")?.let { s ->
                    extractContinuationToken(s.arr("continuations")) ?: extractContinuationToken(s.arr("contents"))
                } ?: secEl.obj("musicPlaylistShelfRenderer")?.let { s ->
                    extractContinuationToken(s.arr("continuations")) ?: extractContinuationToken(s.arr("contents"))
                } ?: secEl.obj("itemSectionRenderer")?.arr("contents")?.firstNotNullOfOrNull { inner ->
                    inner.obj("gridRenderer")?.let { g ->
                        extractContinuationToken(g.arr("continuations")) ?: extractContinuationToken(g.arr("items"))
                    } ?: inner.obj("musicShelfRenderer")?.let { s ->
                        extractContinuationToken(s.arr("continuations")) ?: extractContinuationToken(s.arr("contents"))
                    } ?: inner.obj("musicPlaylistShelfRenderer")?.let { s ->
                        extractContinuationToken(s.arr("continuations")) ?: extractContinuationToken(s.arr("contents"))
                    }
                }
            }
            ?: extractContinuationToken(selectedTabContent?.obj("gridRenderer")?.arr("continuations"))
            ?: extractContinuationToken(selectedTabContent?.obj("gridRenderer")?.arr("items"))
            ?: extractContinuationToken(selectedTabContent?.obj("musicShelfRenderer")?.arr("continuations"))
            ?: extractContinuationToken(selectedTabContent?.obj("musicShelfRenderer")?.arr("contents"))

        return HomePage(
            sections = sections,
            chips = chips,
            continuation = continuation,
        )
    }

    fun parseHomeContinuation(root: JsonObject): HomePage {
        captureVisitorData(root)
        val sections = mutableListOf<HomeSection>()
        var nextToken: String? = null

        val sectionListCont = root.obj("continuationContents")?.obj("sectionListContinuation")
        if (sectionListCont != null) {
            sectionListCont.arr("contents")?.forEach { el ->
                val itemSecContents = el.obj("itemSectionRenderer")?.arr("contents")
                if (itemSecContents != null) {
                    itemSecContents.forEach { innerEl ->
                        parseHomeSection(innerEl)?.takeIf { it.items.isNotEmpty() }?.let(sections::add)
                    }
                } else {
                    parseHomeSection(el)?.takeIf { it.items.isNotEmpty() }?.let(sections::add)
                }
            }
            nextToken = extractContinuationToken(sectionListCont.arr("continuations"))
        }

        val musicShelfCont = root.obj("continuationContents")?.obj("musicShelfContinuation")
            ?: root.obj("continuationContents")?.obj("musicPlaylistShelfContinuation")
        if (musicShelfCont != null) {
            val items = musicShelfCont.arr("contents")
                ?.mapNotNull {
                    it.obj("musicResponsiveListItemRenderer")?.let(::parseResponsiveListItem)
                        ?: it.obj("musicTwoRowItemRenderer")?.let(::parseTwoRowItem)
                }
                .orEmpty()
            if (items.isNotEmpty()) {
                sections.add(HomeSection(title = "More picks", items = items))
            }
            if (nextToken == null) {
                nextToken = extractContinuationToken(musicShelfCont.arr("continuations"))
                    ?: extractContinuationToken(musicShelfCont.arr("contents"))
            }
        }

        val gridCont = root.obj("continuationContents")?.obj("gridContinuation")
        if (gridCont != null) {
            val items = gridCont.arr("items")
                ?.mapNotNull {
                    it.obj("musicTwoRowItemRenderer")?.let(::parseTwoRowItem)
                        ?: it.obj("musicResponsiveListItemRenderer")?.let(::parseResponsiveListItem)
                }
                .orEmpty()
            if (items.isNotEmpty()) {
                sections.add(HomeSection(title = "Library", items = items))
            }
            if (nextToken == null) {
                nextToken = extractContinuationToken(gridCont.arr("continuations"))
                    ?: extractContinuationToken(gridCont.arr("items"))
            }
        }

        // Also check onResponseReceivedActions / appendContinuationItemsAction / reloadContinuationItemsCommand
        if (sections.isEmpty()) {
            root.arr("onResponseReceivedActions")?.forEach { action ->
                val appendItems = action.obj("appendContinuationItemsAction")?.arr("continuationItems")
                    ?: action.obj("reloadContinuationItemsCommand")?.arr("continuationItems")
                appendItems?.forEach { el ->
                    val itemSecContents = el.obj("itemSectionRenderer")?.arr("contents")
                    if (itemSecContents != null) {
                        itemSecContents.forEach { innerEl ->
                            parseHomeSection(innerEl)?.takeIf { it.items.isNotEmpty() }?.let(sections::add)
                        }
                    } else {
                        parseHomeSection(el)?.takeIf { it.items.isNotEmpty() }?.let(sections::add)
                    }
                }
                if (nextToken == null) {
                    nextToken = extractContinuationToken(appendItems)
                }
            }
        }

        return HomePage(
            sections = sections,
            chips = emptyList(),
            continuation = nextToken,
        )
    }

    private fun parseHomeSection(sectionEl: JsonElement): HomeSection? {
        sectionEl.obj("itemSectionRenderer")?.arr("contents")?.forEach { inner ->
            parseHomeSection(inner)?.let { return it }
        }
        sectionEl.obj("musicCarouselShelfRenderer")?.let { return parseCarouselShelf(it) }
        sectionEl.obj("musicShelfRenderer")?.let { return parseMusicShelf(it) }
        sectionEl.obj("musicPlaylistShelfRenderer")?.let { return parseMusicShelf(it) }
        sectionEl.obj("musicCardShelfRenderer")?.let { return parseCardShelf(it) }
        sectionEl.obj("gridRenderer")?.let { return parseGridShelf(it) }
        return null
    }

    private fun parseCarouselShelf(carousel: JsonObject): HomeSection? {
        val header = carousel.obj("header")?.obj("musicCarouselShelfBasicHeaderRenderer")
        val title = header?.runsText("title").orEmpty()
        val strapline = header?.runsText("strapline")
        val contents = carousel.arr("contents") ?: return null
        val items = contents.mapNotNull { itemEl ->
            itemEl.obj("musicTwoRowItemRenderer")?.let { parseTwoRowItem(it) }
                ?: itemEl.obj("musicResponsiveListItemRenderer")?.let { parseResponsiveListItem(it) }
        }
        if (items.isEmpty()) return null
        return HomeSection(
            title = title.ifBlank { "Recommended" },
            label = strapline,
            items = filterPlayableHomeItems(title, items),
        )
    }

    private fun parseMusicShelf(shelf: JsonObject): HomeSection? {
        val title = shelf.runsText("title").orEmpty()
        val strapline = shelf.runsText("strapline")
        val contents = shelf.arr("contents") ?: return null
        val items = contents.mapNotNull { itemEl ->
            itemEl.obj("musicResponsiveListItemRenderer")?.let { parseResponsiveListItem(it) }
                ?: itemEl.obj("musicTwoRowItemRenderer")?.let { parseTwoRowItem(it) }
        }
        if (items.isEmpty()) return null
        return HomeSection(
            title = title.ifBlank { "Quick picks" },
            label = strapline,
            items = filterPlayableHomeItems(title, items),
        )
    }

    private fun parseCardShelf(cardShelf: JsonObject): HomeSection? {
        val header = cardShelf.obj("header")?.obj("musicCardShelfHeaderBasicRenderer")
        val title = header?.runsText("title") ?: cardShelf.runsText("title") ?: "Featured"
        val strapline = header?.runsText("strapline")
        val items = mutableListOf<YTItem>()

        // The main card itself can be an album/playlist/song
        val cardTitle = cardShelf.runsText("title")
        val cardSub = cardShelf.runsText("subtitle")
        val cardThumb = upscaleThumbnail(
            cardShelf.obj("thumbnail")?.obj("musicThumbnailRenderer")?.thumbnailUrl()
        )
        val nav = cardShelf.obj("title")?.obj("runs")?.let { null }
            ?: cardShelf.obj("onTap")
        val browseId = nav?.obj("browseEndpoint")?.str("browseId")
        val watchEndpoint = nav?.obj("watchEndpoint")
        if (!cardTitle.isNullOrBlank() && !cardThumb.isNullOrBlank()) {
            when {
                browseId != null && browseId.startsWith("MPRE") -> {
                    items.add(
                        AlbumItem(
                            browseId = browseId,
                            playlistId = watchEndpoint?.str("playlistId") ?: browseId,
                            title = cardTitle,
                            artists = cardSub?.let { listOf(Artist(it, null)) },
                            thumbnail = cardThumb,
                        )
                    )
                }
                browseId != null && (browseId.startsWith("VL") || browseId.startsWith("RD")) -> {
                    val plId = browseId.removePrefix("VL")
                    items.add(
                        PlaylistItem(
                            id = plId,
                            title = cardTitle,
                            author = cardSub?.let { Artist(it, null) },
                            songCountText = null,
                            thumbnail = cardThumb,
                            playEndpoint = WatchEndpoint(playlistId = plId),
                            shuffleEndpoint = null,
                            radioEndpoint = null,
                        )
                    )
                }
                watchEndpoint?.str("videoId") != null -> {
                    val vid = watchEndpoint.str("videoId")!!
                    items.add(
                        SongItem(
                            id = vid,
                            title = cardTitle,
                            artists = listOf(Artist(cardSub ?: "YouTube Music", null)),
                            thumbnail = cardThumb,
                            endpoint = WatchEndpoint(videoId = vid),
                        )
                    )
                }
            }
        }

        cardShelf.arr("contents")?.forEach { el ->
            el.obj("musicResponsiveListItemRenderer")?.let(::parseResponsiveListItem)?.let(items::add)
            el.obj("musicTwoRowItemRenderer")?.let(::parseTwoRowItem)?.let(items::add)
        }

        if (items.isEmpty()) return null
        return HomeSection(
            title = title,
            label = strapline,
            items = items,
        )
    }

    private fun parseGridShelf(grid: JsonObject): HomeSection? {
        val header = grid.obj("header")?.obj("gridHeaderRenderer")
        val title = header?.runsText("title").orEmpty()
        val items = grid.arr("items")?.mapNotNull { el ->
            el.obj("musicTwoRowItemRenderer")?.let(::parseTwoRowItem)
                ?: el.obj("musicResponsiveListItemRenderer")?.let(::parseResponsiveListItem)
        }.orEmpty()
        if (items.isEmpty()) return null
        return HomeSection(
            title = title.ifBlank { "Featured" },
            items = items,
        )
    }

    /**
     * Filter out unplayable video-compilation dead-end items when a shelf is a video shelf.
     */
    private fun filterPlayableHomeItems(shelfTitle: String, items: List<YTItem>): List<YTItem> {
        val lowerTitle = shelfTitle.lowercase()
        val isVideoShelf = lowerTitle.contains("music video") || lowerTitle.contains("videos for you")
        return if (isVideoShelf) {
            // Keep songs (which play audio via videoId) and standard albums/playlists/artists
            items.filter { item ->
                when (item) {
                    is SongItem -> item.id.isNotBlank()
                    is AlbumItem -> item.browseId.isNotBlank()
                    is PlaylistItem -> item.id.isNotBlank()
                    is ArtistItem -> item.id.isNotBlank()
                    else -> true
                }
            }
        } else {
            items
        }
    }

    // -------------------------------------------------------------------------
    // Two-row card item (`musicTwoRowItemRenderer`) & Responsive list item (`musicResponsiveListItemRenderer`)
    // -------------------------------------------------------------------------

    fun parseTwoRowItem(r: JsonObject): YTItem? {
        val title = r.runsText("title") ?: return null
        val subtitleRuns = r.obj("subtitle")?.arr("runs")
        val subtitle = subtitleRuns?.joinToString("") { it.str("text").orEmpty() }.orEmpty()
        val thumb = upscaleThumbnail(
            r.obj("thumbnailRenderer")?.obj("musicThumbnailRenderer")?.thumbnailUrl()
        ).orEmpty()

        val nav = r.obj("navigationEndpoint")
        val browseEndpoint = nav?.obj("browseEndpoint")
        val browseId = browseEndpoint?.str("browseId")
        val pageType = browseEndpoint
            ?.obj("browseEndpointContextSupportedConfigs")
            ?.obj("browseEndpointContextMusicConfig")
            ?.str("pageType")

        val overlayPlayNav = r.obj("thumbnailOverlay")
            ?.obj("musicItemThumbnailOverlayRenderer")
            ?.obj("content")
            ?.obj("musicPlayButtonRenderer")
            ?.obj("playNavigationEndpoint")
        val overlayWatch = overlayPlayNav?.obj("watchEndpoint") ?: overlayPlayNav?.obj("watchPlaylistEndpoint")
        val directWatch = nav?.obj("watchEndpoint") ?: nav?.obj("watchPlaylistEndpoint")
        val watch = directWatch ?: overlayWatch

        val explicit = r.arr("subtitleBadges")?.any {
            it.obj("musicInlineBadgeRenderer")?.obj("icon")?.str("iconType") == "MUSIC_EXPLICIT_BADGE"
        } == true

        val artistsFromRuns = subtitleRuns
            ?.mapNotNull { run ->
                val text = run.str("text")?.trim()?.takeIf { it.isNotEmpty() && it != " • " && it != " & " && it != ", " }
                    ?: return@mapNotNull null
                val bId = run.obj("navigationEndpoint")?.obj("browseEndpoint")?.str("browseId")
                if (bId != null && bId.startsWith("UC")) {
                    Artist(text, bId)
                } else if (!isMetadataNoise(text)) {
                    Artist(text, null)
                } else null
            }.orEmpty()

        val yearFromRuns = subtitleRuns
            ?.mapNotNull { it.str("text")?.trim() }
            ?.firstOrNull { YEAR_REGEX.matches(it) }
            ?.toIntOrNull()

        return when {
            // Album
            (browseId != null && (browseId.startsWith("MPRE") || browseId.startsWith("OLAK") || browseId.startsWith("FEmusic_library_privately_owned_release_detail") || pageType == "MUSIC_PAGE_TYPE_ALBUM" || pageType == "MUSIC_PAGE_TYPE_AUDIOBOOK")) -> {
                val playlistId = watch?.str("playlistId") ?: browseId
                AlbumItem(
                    browseId = browseId,
                    playlistId = playlistId,
                    title = title,
                    artists = artistsFromRuns.ifEmpty {
                        subtitle.split("•").lastOrNull()?.trim()?.takeIf { it.isNotBlank() }?.let { listOf(Artist(it, null)) }
                    },
                    year = yearFromRuns,
                    thumbnail = thumb,
                    explicit = explicit,
                )
            }
            // Artist (also handles YouTube Music library artists whose browseId is "MPLAUC..." with MUSIC_PAGE_TYPE_LIBRARY_ARTIST)
            (browseId != null && (browseId.startsWith("UC") || browseId.startsWith("MPLA") || pageType == "MUSIC_PAGE_TYPE_ARTIST" || pageType == "MUSIC_PAGE_TYPE_LIBRARY_ARTIST" || pageType == "MUSIC_PAGE_TYPE_USER_CHANNEL")) -> {
                val artistId = browseId.removePrefix("MPLA")
                ArtistItem(
                    id = artistId,
                    title = title,
                    thumbnail = thumb,
                    shuffleEndpoint = watch?.str("playlistId")?.let { WatchEndpoint(playlistId = it) },
                    radioEndpoint = WatchEndpoint(playlistId = "RDEM$artistId"),
                )
            }
            // Playlist / Radio / Mix / Liked Music
            (browseId != null && (browseId.startsWith("VL") || browseId.startsWith("RD") || browseId.startsWith("PL") || browseId == "FEmusic_liked_videos" || pageType == "MUSIC_PAGE_TYPE_PLAYLIST")) -> {
                val cleanPlId = if (browseId == "FEmusic_liked_videos") "LM" else browseId.removePrefix("VL")
                val authorText = subtitle.split("•").firstOrNull()?.trim()?.takeIf { it.isNotBlank() && !it.equals("Playlist", ignoreCase = true) }
                PlaylistItem(
                    id = cleanPlId,
                    title = title,
                    author = authorText?.let { Artist(it, null) },
                    songCountText = subtitle.takeIf { it.isNotBlank() },
                    thumbnail = thumb,
                    playEndpoint = watch?.str("playlistId")?.let { WatchEndpoint(playlistId = it) } ?: WatchEndpoint(playlistId = cleanPlId),
                    shuffleEndpoint = WatchEndpoint(playlistId = cleanPlId, params = "wAEB8gECKAE%3D"),
                    radioEndpoint = WatchEndpoint(playlistId = "RDAMPL$cleanPlId"),
                )
            }
            // Watch Playlist / Mix without browseId (e.g., Supermix, My Mix, Radio card)
            (watch?.str("videoId") == null && watch?.str("playlistId") != null) -> {
                val plId = watch.str("playlistId")!!.removePrefix("VL")
                PlaylistItem(
                    id = plId,
                    title = title,
                    author = subtitle.takeIf { it.isNotBlank() }?.let { Artist(it, null) },
                    songCountText = subtitle.takeIf { it.isNotBlank() },
                    thumbnail = thumb,
                    playEndpoint = WatchEndpoint(playlistId = plId, params = watch.str("params")),
                    shuffleEndpoint = null,
                    radioEndpoint = null,
                )
            }
            // Song / Video / Radio with videoId
            (watch?.str("videoId") != null) -> {
                val videoId = watch.str("videoId")!!
                val playlistId = watch.str("playlistId")
                // If it's a station/mix tile whose title ends with "Mix" or "Radio" and has an RD* playlist,
                // keep it as a SongItem if it's a normal track, or PlaylistItem if it's a Mix/Station card.
                val isMixCard = playlistId != null &&
                    (playlistId.startsWith("RDCLAK") || playlistId.startsWith("RDTMAK") ||
                        ((playlistId.startsWith("RDAMVM") || playlistId.startsWith("RDEM")) &&
                            (title.contains("Mix", ignoreCase = true) || title.contains("Radio", ignoreCase = true) || subtitle.contains("Mix", ignoreCase = true))))
                if (isMixCard) {
                    val stationId = if (playlistId!!.startsWith("RDAMVM")) "RDAMVM$videoId" else playlistId.removePrefix("VL")
                    PlaylistItem(
                        id = stationId,
                        title = title,
                        author = subtitle.takeIf { it.isNotBlank() }?.let { Artist(it, null) },
                        songCountText = subtitle,
                        thumbnail = thumb,
                        playEndpoint = WatchEndpoint(videoId = videoId, playlistId = playlistId),
                        shuffleEndpoint = null,
                        radioEndpoint = null,
                    )
                } else {
                    val artistList = artistsFromRuns.ifEmpty {
                        val cleaned = subtitle.split("•")
                            .map { it.trim() }
                            .firstOrNull { it.isNotEmpty() && !isMetadataNoise(it) }
                            ?: "YouTube Music"
                        listOf(Artist(cleaned, null))
                    }
                    SongItem(
                        id = videoId,
                        title = title,
                        artists = artistList,
                        thumbnail = thumb.ifBlank { "https://i.ytimg.com/vi/$videoId/hqdefault.jpg" },
                        explicit = explicit,
                        endpoint = WatchEndpoint(
                            videoId = videoId,
                            playlistId = playlistId,
                            params = watch.str("params"),
                        ),
                    )
                }
            }
            else -> null
        }
    }

    fun parseResponsiveListItem(
        r: JsonObject,
        fallbackArtist: Artist? = null,
        fallbackAlbum: Album? = null,
        fallbackThumb: String? = null,
    ): YTItem? {
        val flex = r.arr("flexColumns") ?: return null
        val titleRun = flex.getOrNull(0)
            ?.obj("musicResponsiveListItemFlexColumnRenderer")
            ?.obj("text")?.arr("runs")?.firstOrNull()
        val title = titleRun?.str("text")?.trim()?.takeIf { it.isNotBlank() } ?: return null

        val thumb = upscaleThumbnail(
            r.obj("thumbnail")?.obj("musicThumbnailRenderer")?.thumbnailUrl()
        ) ?: fallbackThumb.orEmpty()

        val explicit = r.arr("badges")?.any {
            it.obj("musicInlineBadgeRenderer")?.obj("icon")?.str("iconType") == "MUSIC_EXPLICIT_BADGE"
        } == true

        val overlayWatch = r.obj("overlay")
            ?.obj("musicItemThumbnailOverlayRenderer")
            ?.obj("content")
            ?.obj("musicPlayButtonRenderer")
            ?.obj("playNavigationEndpoint")
            ?.let { it.obj("watchEndpoint") ?: it.obj("watchPlaylistEndpoint") }

        val nav = r.obj("navigationEndpoint")
        val directWatch = nav?.obj("watchEndpoint") ?: nav?.obj("watchPlaylistEndpoint")
        val titleWatch = titleRun.obj("navigationEndpoint")?.obj("watchEndpoint")

        val browseEp = nav?.obj("browseEndpoint") ?: titleRun.obj("navigationEndpoint")?.obj("browseEndpoint")
        val browseId = browseEp?.str("browseId")
        val pageType = browseEp?.obj("browseEndpointContextSupportedConfigs")
            ?.obj("browseEndpointContextMusicConfig")
            ?.str("pageType")

        // Collect all runs across secondary flexColumns and fixedColumns
        val secondaryRuns = flex.drop(1).flatMap { col ->
            col.obj("musicResponsiveListItemFlexColumnRenderer")
                ?.obj("text")?.arr("runs")
                ?.mapNotNull { it as? JsonObject }
                .orEmpty()
        }
        val fixedRuns = r.arr("fixedColumns").orEmpty().flatMap { col ->
            col.obj("musicResponsiveListItemFixedColumnRenderer")
                ?.obj("text")?.arr("runs")
                ?.mapNotNull { it as? JsonObject }
                .orEmpty()
        }
        val allMetaRuns = secondaryRuns + fixedRuns

        val artists = mutableListOf<Artist>()
        var album: Album? = fallbackAlbum
        var durationSec: Int? = null
        val subtitleText = secondaryRuns.joinToString("") { it.str("text").orEmpty() }.trim()

        for (run in allMetaRuns) {
            val text = run.str("text")?.trim() ?: continue
            if (text.isEmpty() || text == "•" || text == "·" || text == "," || text == "&") continue
            if (durationSec == null && DURATION_REGEX.matches(text)) {
                durationSec = parseDurationSeconds(text)
                continue
            }
            val runBrowseEp = run.obj("navigationEndpoint")?.obj("browseEndpoint")
            val bId = runBrowseEp?.str("browseId")
            val pType = runBrowseEp?.obj("browseEndpointContextSupportedConfigs")
                ?.obj("browseEndpointContextMusicConfig")
                ?.str("pageType")

            when {
                bId != null && (bId.startsWith("MPRE") || bId.startsWith("OLAK") || pType == "MUSIC_PAGE_TYPE_ALBUM") -> {
                    if (album == null) album = Album(text, bId)
                }
                bId != null && (bId.startsWith("UC") || bId.startsWith("MPLA") || pType == "MUSIC_PAGE_TYPE_ARTIST" || pType == "MUSIC_PAGE_TYPE_LIBRARY_ARTIST" || pType == "MUSIC_PAGE_TYPE_USER_CHANNEL") -> {
                    val artistId = bId.removePrefix("MPLA")
                    if (artists.none { it.name.equals(text, ignoreCase = true) }) {
                        artists.add(Artist(text, artistId))
                    }
                }
                artists.isEmpty() && !isMetadataNoise(text) -> {
                    artists.add(Artist(text, null))
                }
            }
        }

        val hasPlaylistItemVideoId = r.obj("playlistItemData")?.str("videoId") != null
        val isExplicitBrowseContainer = !hasPlaylistItemVideoId && browseId != null && (
            browseId.startsWith("MPRE") ||
                browseId.startsWith("OLAK") ||
                browseId.startsWith("FEmusic_library_privately_owned_release_detail") ||
                browseId.startsWith("VL") ||
                browseId.startsWith("PL") ||
                browseId.startsWith("RD") ||
                browseId.startsWith("UC") ||
                browseId.startsWith("MPLA") ||
                browseId == "FEmusic_liked_videos" ||
                pageType == "MUSIC_PAGE_TYPE_ALBUM" ||
                pageType == "MUSIC_PAGE_TYPE_AUDIOBOOK" ||
                pageType == "MUSIC_PAGE_TYPE_PLAYLIST" ||
                pageType == "MUSIC_PAGE_TYPE_ARTIST" ||
                pageType == "MUSIC_PAGE_TYPE_LIBRARY_ARTIST" ||
                pageType == "MUSIC_PAGE_TYPE_USER_CHANNEL"
            )

        if (isExplicitBrowseContainer && browseId != null) {
            return when {
                browseId.startsWith("UC") || browseId.startsWith("MPLA") || pageType == "MUSIC_PAGE_TYPE_ARTIST" || pageType == "MUSIC_PAGE_TYPE_LIBRARY_ARTIST" || pageType == "MUSIC_PAGE_TYPE_USER_CHANNEL" -> {
                    val artistId = browseId.removePrefix("MPLA")
                    ArtistItem(
                        id = artistId,
                        title = title,
                        thumbnail = thumb,
                        shuffleEndpoint = null,
                        radioEndpoint = WatchEndpoint(playlistId = "RDEM$artistId"),
                    )
                }
                browseId.startsWith("MPRE") || browseId.startsWith("OLAK") || browseId.startsWith("FEmusic_library_privately_owned_release_detail") || pageType == "MUSIC_PAGE_TYPE_ALBUM" || pageType == "MUSIC_PAGE_TYPE_AUDIOBOOK" -> {
                    val plId = (directWatch ?: overlayWatch)?.str("playlistId") ?: browseId
                    AlbumItem(
                        browseId = browseId,
                        playlistId = plId,
                        title = title,
                        artists = artists.ifEmpty { null },
                        thumbnail = thumb,
                        explicit = explicit,
                    )
                }
                browseId.startsWith("VL") || browseId.startsWith("RD") || browseId.startsWith("PL") || browseId == "FEmusic_liked_videos" || pageType == "MUSIC_PAGE_TYPE_PLAYLIST" -> {
                    val cleanPlId = if (browseId == "FEmusic_liked_videos") "LM" else browseId.removePrefix("VL")
                    PlaylistItem(
                        id = cleanPlId,
                        title = title,
                        author = artists.firstOrNull(),
                        songCountText = subtitleText.takeIf { it.isNotBlank() },
                        thumbnail = thumb,
                        playEndpoint = WatchEndpoint(playlistId = cleanPlId),
                        shuffleEndpoint = null,
                        radioEndpoint = null,
                    )
                }
                else -> null
            }
        }

        val videoId = r.obj("playlistItemData")?.str("videoId")
            ?: directWatch?.str("videoId")
            ?: overlayWatch?.str("videoId")
            ?: titleWatch?.str("videoId")

        val setVideoId = r.obj("playlistItemData")?.str("playlistSetVideoId")

        if (videoId != null) {
            val finalArtists = artists.ifEmpty {
                listOfNotNull(fallbackArtist).ifEmpty { listOf(Artist("YouTube Music", null)) }
            }
            val finalThumb = thumb.ifBlank { "https://i.ytimg.com/vi/$videoId/hqdefault.jpg" }
            val playlistId = (directWatch ?: overlayWatch)?.str("playlistId")
            return SongItem(
                id = videoId,
                title = title,
                artists = finalArtists,
                album = album,
                duration = durationSec,
                thumbnail = finalThumb,
                explicit = explicit,
                endpoint = WatchEndpoint(
                    videoId = videoId,
                    playlistId = playlistId,
                ),
                setVideoId = setVideoId,
            )
        }

        if (browseId == null) return null

        return when {
            browseId.startsWith("UC") || browseId.startsWith("MPLA") || pageType == "MUSIC_PAGE_TYPE_ARTIST" || pageType == "MUSIC_PAGE_TYPE_LIBRARY_ARTIST" || pageType == "MUSIC_PAGE_TYPE_USER_CHANNEL" -> {
                val artistId = browseId.removePrefix("MPLA")
                ArtistItem(
                    id = artistId,
                    title = title,
                    thumbnail = thumb,
                    shuffleEndpoint = null,
                    radioEndpoint = WatchEndpoint(playlistId = "RDEM$artistId"),
                )
            }
            browseId.startsWith("MPRE") || browseId.startsWith("OLAK") || pageType == "MUSIC_PAGE_TYPE_ALBUM" -> {
                val plId = (directWatch ?: overlayWatch)?.str("playlistId") ?: browseId
                AlbumItem(
                    browseId = browseId,
                    playlistId = plId,
                    title = title,
                    artists = artists.ifEmpty { null },
                    thumbnail = thumb,
                    explicit = explicit,
                )
            }
            browseId.startsWith("VL") || browseId.startsWith("RD") || browseId.startsWith("PL") || browseId == "FEmusic_liked_videos" || pageType == "MUSIC_PAGE_TYPE_PLAYLIST" -> {
                val cleanPlId = if (browseId == "FEmusic_liked_videos") "LM" else browseId.removePrefix("VL")
                PlaylistItem(
                    id = cleanPlId,
                    title = title,
                    author = artists.firstOrNull(),
                    songCountText = subtitleText.takeIf { it.isNotBlank() },
                    thumbnail = thumb,
                    playEndpoint = WatchEndpoint(playlistId = cleanPlId),
