    }

    // -------------------------------------------------------------------------
    // Helpers
    // -------------------------------------------------------------------------

    private fun extractContinuationToken(continuations: JsonArray?): String? {
        if (continuations == null) return null
        for (el in continuations) {
            val obj = el as? JsonObject ?: continue
            obj.obj("nextContinuationData")?.str("continuation")?.takeIf { it.isNotBlank() }?.let { return it }
            obj.obj("nextRadioContinuationData")?.str("continuation")?.takeIf { it.isNotBlank() }?.let { return it }
            obj.obj("reloadContinuationData")?.str("continuation")?.takeIf { it.isNotBlank() }?.let { return it }
            obj.obj("continuationItemRenderer")
                ?.obj("continuationEndpoint")
                ?.obj("continuationCommand")
                ?.str("token")
                ?.takeIf { it.isNotBlank() }
                ?.let { return it }
        }
        return null
    }

    private fun parseDurationSeconds(text: String): Int? {
        val parts = text.trim().split(":").map { it.toIntOrNull() ?: return null }
        return when (parts.size) {
            2 -> parts[0] * 60 + parts[1]
            3 -> parts[0] * 3600 + parts[1] * 60 + parts[2]
            else -> null
        }
    }

    private fun JsonElement?.obj(key: String): JsonObject? =
        (this as? JsonObject)?.get(key) as? JsonObject

    private fun JsonElement?.arr(key: String): JsonArray? =
        (this as? JsonObject)?.get(key) as? JsonArray

    private fun JsonElement?.str(key: String): String? =
        ((this as? JsonObject)?.get(key) as? JsonPrimitive)?.contentOrNull

    private fun JsonElement?.long(key: String): Long? =
        ((this as? JsonObject)?.get(key) as? JsonPrimitive)?.longOrNull

    private fun JsonObject.runsText(key: String): String? {
        val field = this[key] as? JsonObject ?: return null
        field.str("simpleText")?.let { return it }
        val runs = field.arr("runs") ?: return null
        return runs.joinToString("") { (it as? JsonObject)?.str("text").orEmpty() }.takeIf { it.isNotEmpty() }
    }

    private fun JsonObject.thumbnailUrl(): String? {
        val thumbs = (this["thumbnails"] as? JsonArray)
            ?: (this["thumbnail"] as? JsonObject)?.arr("thumbnails")
            ?: return null
        return (thumbs.lastOrNull() as? JsonObject)?.str("url")
    }
